def cmd_field_census():
    """Report every string/list-of-string key in maps, bucketed. Drift guard."""
    inc, exc, unknown = collections.Counter(), collections.Counter(), collections.Counter()

    def walk(o):
        if isinstance(o, dict):
            for k, v in o.items():
                if k in SKIP_SUBTREES:
                    continue
                if isinstance(v, str) or (isinstance(v, list) and v and
                                          all(isinstance(x, str) for x in v)):
                    n = 1 if isinstance(v, str) else len(v)
                    if k.startswith("_"):
                        exc[k] += n
                    elif is_prose_key(k):
                        inc[k] += n
                    elif k in KNOWN_NON_PROSE:
                        exc[k] += n
                    else:
                        unknown[k] += n
                if not isinstance(v, str):
                    walk(v)
        elif isinstance(o, list):
            for x in o:
                walk(x)

    for f in sorted(MAPS.glob("**/*.json")):
        walk(rjson(f))
    print("MAPS -- INCLUDED prose keys:")
    for k, c in sorted(inc.items()):
        star = "" if (k in MAP_PROSE_KEYS or k in TOAST_KEYS_SEEN) else "  <-- NEW TOAST KEY"
        print(f"  {c:5}  {k}{star}")
    print(f"  TOTAL {sum(inc.values())}")
    print("\nMAPS -- UNKNOWN keys (neither prose nor known-structural -- TRIAGE):")
    for k, c in sorted(unknown.items()):
        print(f"  {c:5}  {k}")
    if not unknown:
        print("  (none)")
    return 1 if unknown else 0


def dialogue_census():
    """Independent path-based census of dialogue string keys. Mirror of the
    maps census (fix I1): a dialogue field the walker does not know about must
    surface as a REPORT, not as silently missing prose.

    -> (included Counter, excluded Counter, unknown Counter, {file: set(paths)})
    """
    inc, exc, unknown = collections.Counter(), collections.Counter(), collections.Counter()
    paths = {}

    def walk(o, keys, path, out):
        if isinstance(o, dict):
            for k, v in o.items():
                walk(v, keys + (k,), f"{path}.{k}", out)
        elif isinstance(o, list):
            for i, v in enumerate(o):
                walk(v, keys, f"{path}[{i}]", out)
        elif isinstance(o, str) and keys:
            k = keys[-1]
            if any(x.startswith("_") for x in keys):
                exc["_author-private"] += 1
            elif len(keys) >= 2 and keys[-2] in DLG_BANK_CONTAINERS:
                inc["text_bank"] += 1
                out.add(path)
            elif k in DLG_PROSE_KEYS:
                if o.startswith("@"):
                    exc["text (@ref = structure)"] += 1
                else:
                    inc["text"] += 1
                    out.add(path)
            elif k in DLG_EFFECT_PROSE_KEYS and DLG_EFFECT_CONTAINER in keys:
                inc["effects[].toast"] += 1
                out.add(path)
            elif k in DLG_KNOWN_NON_PROSE:
                exc[k] += 1
            else:
                unknown[k] += 1

    for f in sorted(GATE.DIALOGUE.glob("*.json")):
        out = set()
        walk(rjson(f), (), "$", out)
        paths[f.name] = out
    return inc, exc, unknown, paths


