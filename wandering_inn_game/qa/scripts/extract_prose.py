def resolve_issue_keeps(rows):
    """-> ({id: record}, [unresolved]). A snippet that matches 0 or >1 strings
    in its file is UNRESOLVED, never guessed at."""
    by_file = collections.defaultdict(list)
    for r in rows:
        by_file[r["file"]].append(r)
    out, unresolved = {}, []
    for path, line, snippet, why in ISSUE_KEEPS:
        hits = [r for r in by_file.get(path, []) if snippet in r["text"]]
        if len(hits) == 1:
            r = hits[0]
            out[r["id"]] = {
                "reason": why,
                "source": "issue counterevidence list (bound by snippet, not line)",
                "file": r["file"],
                "field_path": r["field_path"],
                "exact_text": r["text"],
            }
        else:
            unresolved.append(f"{path} ~line {line}: {len(hits)} snippet matches")
    return out, unresolved


