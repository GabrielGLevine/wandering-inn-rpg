# ---- self-test ---------------------------------------------------------------
def self_test():
    fails = []

    def check(name, ok, detail=""):
        print(f"  {'ok  ' if ok else 'FAIL'} {name}{'  ' + detail if detail else ''}")
        if not ok:
            fails.append(name)

    # 1. the two map walkers must never overlap
    overlap = []
    for f in sorted(MAPS.glob("**/*.json")):
        d = rjson(f)
        a = {p for p, _ in GATE.walk_map_texts(d)}
        b = {p for p, _, _, _ in walk_map_prose(d)}
        if a & b:
            overlap.append((f.name, sorted(a & b)[:3]))
    check("map walkers disjoint (GH#388 talk vs GH#397 prose)", not overlap,
          str(overlap[:2]))

    # 1a. MIRROR CONTRACT with the gate's GH#397 prose-field mask (H2). The gate
    #     masks these exact fields out of its frozen map skeleton so a #397 prose
    #     edit is not a structural diff. If this file's field list grows and the
    #     gate's does not, the maps gate starts hard-failing legitimate prose
    #     edits again (the H2 bug, returning); if the GATE's grows first, it
    #     stops freezing a field nothing else guards. Neither may drift silently.
    check("gate prose-field mask mirrors MAP_PROSE_KEYS",
          GATE.MAP_PROSE_KEYS_397 == MAP_PROSE_KEYS,
          f"gate={sorted(GATE.MAP_PROSE_KEYS_397)} vs ours={sorted(MAP_PROSE_KEYS)}")
    mask_drift = [k for k in sorted(TOAST_KEYS_SEEN) if not GATE.is_prose_key_397(k)]
    check("gate prose-field mask covers every seen toast key",
          not mask_drift, str(mask_drift))
    mask_wide = [k for k in sorted(KNOWN_NON_PROSE) if GATE.is_prose_key_397(k)]
    check("gate prose-field mask masks no known NON-prose key",
          not mask_wide, str(mask_wide))
    # And the masker itself must be exactly as wide as OUR walker: every string
    # walk_map_prose claims is a masked slot in the gate's skeleton, and nothing
    # else is. This is the fence measured on the REAL corpus, not on the lists.
    mism = []
    for f in sorted(MAPS.glob("**/*.json")):
        d = rjson(f)
        sk = GATE.map_skeleton(d)
        for p, _, _, _ in walk_map_prose(d):
            if resolve_path(sk, p) != GATE.MASK_397:
                mism.append(f"{f.name}{p} not masked")
        for p, _ in GATE.walk_map_texts(d):
            if resolve_path(sk, p) == GATE.MASK_397:
                mism.append(f"{f.name}{p} talk slot got the PROSE mask")
    check("every walk_map_prose string is a masked slot in the gate skeleton",
          not mism, str(mism[:3]))

    # 1b. same for the dialogue side: our effect-toast walker must not restate
    #     anything GATE.walk_texts already owns.
    dlg_overlap = []
    for f in sorted(GATE.DIALOGUE.glob("*.json")):
        d = rjson(f)
        a = {p for p, _ in GATE.walk_texts(d)}
        b = {p for p, _ in walk_dialogue_effect_prose(d)}
        if a & b:
            dlg_overlap.append((f.name, sorted(a & b)[:3]))
    check("dialogue walkers disjoint (gate text vs effect toasts)",
          not dlg_overlap, str(dlg_overlap[:2]))

    # 2. ballpark reconciliation with the issue's audit
    rows = build_inventory()
    d = [r for r in rows if r["corpus"] == "dialogue"]
    m = [r for r in rows if r["corpus"] == "maps"]
    dw, mw = sum(r["word_count"] for r in d), sum(r["word_count"] for r in m)
    check("dialogue strings within 5% of issue's 1482",
          abs(len(d) - 1482) / 1482 < 0.05, f"{len(d)}")
    check("dialogue words within 5% of issue's 24.5k",
          abs(dw - 24500) / 24500 < 0.05, f"{dw}")
    check("map strings within 5% of issue's 825",
          abs(len(m) - 825) / 825 < 0.05, f"{len(m)}")
    check("map words within 8% of issue's 18.5k",
          abs(mw - 18500) / 18500 < 0.08, f"{mw}")

    # 2b. the option-effect toasts the gate does not walk (fix I1)
    eff = [r for r in d if r["field"] == "toast"]
    check("dialogue option-effect toasts are in the inventory", len(eff) == 7,
          f"{len(eff)} (expect 7; wi_game.gd:1408-1412 renders them)")
    check("every effect toast sits on an options[].effects[] path",
          all(".options[" in r["field_path"] and ".effects[" in r["field_path"]
              for r in eff))

    # 3. round-trip: every inventory text is findable verbatim in its file
    #    (as the JSON-escaped form -- \" and \n live escaped on disk)
    #    Either escaping form counts: most files carry literal em-dashes, but
    #    rags_meeting.json writes its own as —.
    src, bad = {}, []
    for r in rows:
        t = src.setdefault(r["file"], rtext(REPO / r["file"]))
        if (json.dumps(r["text"], ensure_ascii=False)[1:-1] not in t
                and json.dumps(r["text"])[1:-1] not in t):
            bad.append(r["id"])
    check("every string round-trips into its source file", not bad, str(bad[:3]))

    # 3a. and every inventory row resolves at its own field path. This is what
    #     makes field_path a safe pin for keeps and verify-untouched.
    mism = [r["id"] for r in rows
            if live_text(r["file"], r["field_path"]) != r["text"]]
    check("every row's field_path resolves to its own text", not mism, str(mism[:3]))

    # 3b. CENSUS CROSS-CHECK (maps): the walker must find every prose-keyed
    #     string the independent key census counts. This is the leg that caught
    #     the 7 sleep_toast conditional-variant strings; keep it.
    #     Independent PATH-BASED rule (no owner-threading, so it cannot share
    #     the walker's bugs): a string is prose iff some key on its path is a
    #     prose key, no key on its path is author-private ("_") or a GH#388
    #     talk subtree, and its own immediate key is not known structure.
    def census(o, keys=(), path="$"):
        if isinstance(o, dict):
            for k, v in o.items():
                yield from census(v, keys + (k,), f"{path}.{k}")
        elif isinstance(o, list):
            for i, v in enumerate(o):
                yield from census(v, keys, f"{path}[{i}]")
        elif isinstance(o, str) and keys:
            if any(k.startswith("_") or k in SKIP_SUBTREES for k in keys):
                return
            if any(is_prose_key(k) for k in keys) and keys[-1] not in KNOWN_NON_PROSE:
                yield path

    missed, extra = [], []
    for f in sorted(MAPS.glob("**/*.json")):
        d0 = rjson(f)
        cpaths = set(census(d0))
        wpaths = {p for p, _, _, _ in walk_map_prose(d0)}
        missed += [f"{f.name}{p}" for p in sorted(cpaths - wpaths)]
        extra += [f"{f.name}{p}" for p in sorted(wpaths - cpaths)]
    check("map walker finds every census-identified prose string", not missed,
          str(missed[:3]))
    check("map walker claims nothing the census rejects", not extra, str(extra[:3]))

    # 3c. CENSUS CROSS-CHECK (dialogue) -- the mirror leg (fix I1). Dialogue
    #     field drift now fails here instead of quietly shrinking the corpus.
    dinc, _, dunknown, dpaths = dialogue_census()
    check("dialogue census has no unknown string keys", not dunknown,
          str(sorted(dunknown)[:5]))
    dmissed, dextra = [], []
    for f in sorted(GATE.DIALOGUE.glob("*.json")):
        d0 = rjson(f)
        wp = {p for p, _, _ in walk_dialogue_prose(d0)}
        cp = dpaths[f.name]
        dmissed += [f"{f.name}{p}" for p in sorted(cp - wp)]
        dextra += [f"{f.name}{p}" for p in sorted(wp - cp)]
    check("dialogue walker finds every census-identified prose string",
          not dmissed, str(dmissed[:3]))
    check("dialogue walker claims nothing the census rejects", not dextra,
          str(dextra[:3]))
    check("dialogue census total == inventory dialogue rows",
          sum(dinc.values()) == len(d), f"{sum(dinc.values())} vs {len(d)}")

    # 4. ids unique
    ids = [r["id"] for r in rows]
    check("inventory ids unique", len(ids) == len(set(ids)),
          f"{len(ids)-len(set(ids))} dupes")

    # 5. determinism: two builds identical
    check("build_inventory deterministic",
          json.dumps(rows, sort_keys=True) ==
          json.dumps(build_inventory(), sort_keys=True))

    # 6. blind sampling deterministic + disjoint from holdout
    b1 = [r["id"] for r in make_blind(rows, "maps")]
    b2 = [r["id"] for r in make_blind(rows, "maps")]
    check("blind sample deterministic under fixed seed", b1 == b2)
    keeps, unres = build_keeps(rows)
    check("all 5 issue counterevidence keeps resolve to ids",
          not unres and len(keeps) >= 5, str(unres))
    named_work, nw_unres = resolve_named_work(rows)
    nw_state = named_work_state(rows)
    nw_done = [e for e, _ in nw_state if e["done"]]
    nw_pending = [e for e, _ in nw_state if not e["done"]]
    # BOTH directions of the done flag (the H1 inversion fix). Landing the ruled
    # work must not turn this green leg red, and retiring an entry without doing
    # the work must not turn a red leg green.
    check("every issue/controller-named work entry matches its done flag",
          not nw_unres, str(nw_unres))
    check(f"the {len(nw_done)} DONE named-work snippets no longer resolve",
          all(not hits for e, hits in nw_state if e["done"]),
          str([e["snippet"] for e, hits in nw_state if e["done"] and hits]))
    check(f"the {len(nw_pending)} PENDING named-work snippets still resolve, "
          "one string each",
          all(len(hits) == 1 for e, hits in nw_state if not e["done"]),
          str([e["snippet"] for e, hits in nw_state
               if not e["done"] and len(hits) != 1]))
    check("only PENDING named work is reserved out of the holdout",
          len(named_work) == len(nw_pending),
          f"{len(named_work)} reserved vs {len(nw_pending)} pending")
    blind_ids = set(b1) | {r["id"] for r in make_blind(rows, "dialogue")}
    hold = set(make_holdout(rows, set(keeps) | set(named_work), blind_ids))
    check("holdout disjoint from blind sets", not (hold & blind_ids))
    check("holdout disjoint from protected keeps", not (hold & set(keeps)))
    check("holdout does not reserve away a named work string",
          not (hold & set(named_work)))
    check("holdout is ~10%", abs(len(hold) / len(rows) - 0.10) < 0.01,
          f"{len(hold)}/{len(rows)}")

    # 6b. holdout eligibility == blind eligibility (fix I6). Without this the
    #     Phase 5 comparison is sample-of-long-strings vs holdout-of-anything.
    by_id = {r["id"]: r for r in rows}
    short = [i for i in hold if by_id[i]["word_count"] < BLIND_MIN_WORDS]
    check(f"every holdout row is >={BLIND_MIN_WORDS} words (same pool as blinds)",
          not short, str(short[:3]))

    # 6d. holdout EXCLUSIONS (#397 riverfarm lane). The mechanism exists so a
    #     holdout string moved by a DIFFERENT merged change does not read as
    #     prose-pass drift. Every leg here is about it not becoming a licence.
    hrec = rjson(DOCS / "holdout.json")
    hcommitted = set(hrec["ids"])
    art_excl = hrec.get("excluded") or {}
    check("every holdout exclusion is a committed holdout id "
          "(an exclusion cannot invent one)",
          not (set(HOLDOUT_EXCLUSIONS) - hcommitted),
          str(sorted(set(HOLDOUT_EXCLUSIONS) - hcommitted)))
    check("no exclusion shrinks the committed inventory "
          "(`ids` keeps every excluded id, `_count` == len(ids))",
          hrec["_count"] == len(hrec["ids"])
          and not (set(HOLDOUT_EXCLUSIONS) - set(hrec["ids"])),
          f"_count {hrec['_count']} vs {len(hrec['ids'])} ids")
    check("the committed `excluded` block and HOLDOUT_EXCLUSIONS agree "
          "(either alone skips nothing)",
          {k: dict(v) for k, v in art_excl.items()}
          == {k: dict(v) for k, v in HOLDOUT_EXCLUSIONS.items()},
          str(sorted(set(art_excl) ^ set(HOLDOUT_EXCLUSIONS))))
    check("every exclusion declares excluded:true + a non-empty reason",
          all(v.get("excluded") is True
              and str(v.get("excluded_reason") or "").strip()
              for v in HOLDOUT_EXCLUSIONS.values()))
    check(f"excluded_ids() resolves all {len(HOLDOUT_EXCLUSIONS)} declared "
          "exclusions", excluded_ids(hrec) == set(HOLDOUT_EXCLUSIONS),
          str(sorted(set(HOLDOUT_EXCLUSIONS) - excluded_ids(hrec))))
    # A malformed or code-only exclusion must SKIP NOTHING. Both directions,
    # because either one alone becomes the laundering path.
    check("an artifact-only exclusion is inert",
          not excluded_ids({"excluded": {
              "map:riverfarm/riverfarm_mill.json:$.entities[5].toast":
              {"excluded": True, "excluded_reason": "hand-added, not in code"}}}))
    check("a code-declared exclusion missing from the artifact is inert",
          not excluded_ids({"ids": sorted(hcommitted)}))
    check("an exclusion without a reason is inert",
          not excluded_ids({"excluded": {
              i: {"excluded": True, "excluded_reason": ""}
              for i in HOLDOUT_EXCLUSIONS}}))
    # An exclusion is only honest if the string ACTUALLY moved: a pre-emptive
    # one on an unmoved string is a standing licence to edit a control-group
    # string later, with the paperwork already filed.
    hbase = {r["id"]: r for r in load_inventory(DOCS / "inventory.jsonl")}
    unmoved = [i for i in HOLDOUT_EXCLUSIONS
               if i in hbase
               and live_text(hbase[i]["file"], hbase[i]["field_path"])
               == hbase[i]["text"]]
    check("no exclusion covers a string that has not moved", not unmoved,
          str(unmoved))
    # ...and the gate it exempts them from still has to pass.
    _vu = io.StringIO()
    with contextlib.redirect_stdout(_vu):
        vu_rc = cmd_verify_untouched(DOCS)
    check("verify-untouched exits 0 on the live tree (exclusions applied)",
          vu_rc == 0, "" if vu_rc == 0 else _vu.getvalue().strip())
    check(f"verify-untouched reports the {len(HOLDOUT_EXCLUSIONS)} exclusion(s) "
          "by count rather than hiding them",
          f"{len(HOLDOUT_EXCLUSIONS)} holdout string(s) EXCLUDED"
          in _vu.getvalue())
    with tempfile.TemporaryDirectory() as td:
        n_all = write_holdout_blind(list(hbase.values()), hrec["ids"], td)
        n_ex = write_holdout_blind(list(hbase.values()), hrec["ids"], td,
                                   excluded_ids(hrec))
        blind = rtext(Path(td) / "sample-holdout-blind.txt")
    check("the blind control instrument drops exactly the excluded rows",
          n_all - n_ex == len(HOLDOUT_EXCLUSIONS) and n_all == len(hrec["ids"]),
          f"{n_all} -> {n_ex}")
    check("no excluded string's baseline text survives in the control view",
          not [i for i in HOLDOUT_EXCLUSIONS
               if i in hbase and " ".join(hbase[i]["text"].split()) in blind])

    # 6c. protected keeps are pinned by TEXT AT FIELD PATH, not by line (I7)
    unpinned = [k for k, v in keeps.items()
                if not (v.get("file") and v.get("field_path") and v.get("exact_text"))]
    check("every protected keep stores {file, field_path, exact_text}",
          not unpinned, str(unpinned[:3]))
    drift = [k for k, v in keeps.items()
             if live_text(v["file"], v["field_path"]) != v["exact_text"]]
    check("live text at every keep's field path equals its exact_text",
          not drift, str(drift[:3]))
    check("no protected keep records a line number",
          not [k for k, v in keeps.items() if re.search(r":\d+$", str(v.get("source", "")))])

    # 7. tell heuristics fire on the issue's own named examples
    check("neg_correction fires on 'Not a prisoner. An ANCHOR'",
          tells("Not a prisoner. An ANCHOR — a twin to the stone.")["neg_correction"] > 0)
    check("closer flags 'In Pallass, that is a document nobody filed.'",
          closer_score("Eleven names carried. One of them has been carried for two "
                       "years and has no repayment column at all. In Pallass, that "
                       "is a document nobody filed.") >= 2)
    check("closer does NOT flag a plain functional line",
          closer_score("A rack of bundled stems, dried long past any use.") < 2)
    check("anon_agent fires on 'Someone carved joy here'",
          tells("Someone carved joy here, and meant it to last.")["anon_agent"] > 0)

    # 8. every classified register is one of the four
    ov = load_overrides()
    cls = {r["id"]: classify_row(r, ov) for r in rows if r["corpus"] == "maps"}
    regs = {v[0] for v in cls.values()}
    check("registers are exactly the four named",
          regs <= {"functional", "scenic", "character-bearing", "landmark"}, str(regs))

    # 8a. skill-outcome is classified by PATH (fix I2)
    su = [r for r in m
          if any(f".{b}." in r["field_path"] for b in SKILL_USE_BLOCKS)]
    check("every on_skill_use/skill_uses string is functional/skill-outcome",
          su and all(cls[r["id"]] == ("functional", "skill-outcome") for r in su),
          f"{len(su)} strings")
    named = [r for r in m if r["field"] in SKILL_OUTCOME_FIELDS]
    check("the named *_toast skill verbs are the same register",
          all(cls[r["id"]] == ("functional", "skill-outcome") for r in named),
          f"{len(named)} strings")

    # 8b. the work queue triggers on ANY of the three signals (fix I3), and any
    #     STILL-PENDING hand-named line carrying a queue_id must be in it. The
    #     fixture ids are read off ISSUE_NAMED_WORK rather than duplicated here:
    #     a second hard-coded copy of the same two strings was the same H1
    #     inversion bug wearing a different hat (it asserted the PRE-FIX string
    #     was still queued, so it too went red when the fix landed).
    hold_or_keep = hold | set(keeps)
    queue = {r["id"] for r in m
             if is_demotion_candidate(cls[r["id"]][0], r["tells"])
             and r["id"] not in hold_or_keep}
    for e in ISSUE_NAMED_WORK:
        if not e["queue_id"]:
            continue
        label = f"{e['file'].rsplit('/', 1)[-1]} {e['snippet']!r}"
        if e["done"]:
            print(f"  note queue fixture retired (work landed): {label} — "
                  f"replacement {'still trips' if e['queue_id'] in queue else 'trips nothing'}")
        else:
            check(f"work queue contains pending named work {label}",
                  e["queue_id"] in queue)
    # A hand-named work string need not be IN the counter-driven queue -- the
    # queue is scoped to functional/scenic register mismatch, and one of the
    # issue's named lines ("which from him is applause") is character-bearing,
    # which is a different kind of fix. What must hold is that none of them is
    # untouchable: a named piece of work can never be locked away.
    check("no hand-named work string is untouchable",
          not (set(named_work) & hold_or_keep),
          str(sorted(set(named_work) & hold_or_keep)))
    check("the functional/scenic named work is in the queue",
          not {i for i in named_work
               if cls[i][0] in ("functional", "scenic")} - queue,
          str(sorted({i for i in named_work
                      if cls[i][0] in ("functional", "scenic")} - queue)))
    # The trigger WIRING is proven on synthetic strings by the three section-7
    # checks above (closer_score / neg_correction / anon_agent each fire), and
    # those never move with the corpus. What this leg used to assert -- that the
    # LIVE queue still holds a member of all three trigger classes -- is the H1
    # inversion again, third instance: emptying a trigger class is the pass
    # SUCCEEDING, and after the #397 keeps fold neg_correction's last queued
    # member became a protected keep (liscor's grate, granted §7.3), so a green
    # leg went red for exactly the right reason. Kept as a REPORT plus the
    # property that does not invert: the queue can never report a trigger
    # outside the ruled three.
    live_trig = {t for r in m if r["id"] in queue
                 for t in demotion_triggers(r["tells"])}
    all_trig = {k for k, _ in DEMOTION_TRIGGERS}
    check("the queue reports no trigger outside the ruled three",
          live_trig <= all_trig, str(sorted(live_trig - all_trig)))
    print("  note live queue trigger classes: "
          f"{sorted(live_trig) or ['none']} of {sorted(all_trig)} "
          "(an empty class = the work landed, not a regression)")

    # 8c. every hand-audit override must BIND to a real inventory id. Without
    #     this leg a mistyped id is a silent no-op (it was, once).
    allids = {r["id"] for r in rows}
    stale = sorted(set(ov) - allids)
    check("every classification override binds to an inventory id", not stale, str(stale))
    check("every override names a register and a why",
          all(o.get("register") and o.get("why") for o in ov.values()))

    # 8d. same guard for lane-added protected keeps
    extra_keeps = load_extra_keeps()
    bad_x = sorted(set(extra_keeps) - allids)
    check("every lane-added protected keep binds to an inventory id",
          not bad_x, str(bad_x))
    check("every lane-added keep names a kind and a reason",
          all(o.get("kind") and o.get("reason") for o in extra_keeps.values()))

    # 9. landmark registry: total coverage, no discretion (fix I10)
    lm_ids = {i for i, v in cls.items() if v[0] == "landmark"}
    check("every landmark string has a ruled disposition",
          not (lm_ids - set(LANDMARK_DISPOSITIONS)),
          str(sorted(lm_ids - set(LANDMARK_DISPOSITIONS))[:3]))
    check("no disposition is recorded for a non-landmark string",
          not (set(LANDMARK_DISPOSITIONS) - lm_ids),
          str(sorted(set(LANDMARK_DISPOSITIONS) - lm_ids)[:3]))
    check("dispositions are KEEP-AS-IS or RESTAGE only",
          {v["disposition"] for v in LANDMARK_DISPOSITIONS.values()}
          <= {"KEEP-AS-IS", "RESTAGE"})
    check("the two CAPS-staged landmarks are the RESTAGE pair",
          {i for i, v in LANDMARK_DISPOSITIONS.items()
           if v["disposition"] == "RESTAGE"}
          == {"map:dungeon/seal_vault.json:$.entities[1].open_toast",
              "map:ruin/ruin_surface.json:$.entities[5].open_toast"})

    # 10. field-path resolver, on the shapes that actually occur
    check("resolve_path handles list indices and nested blocks",
          live_text("wandering_inn_game/data/maps/ruin/ruin_surface.json",
                    "$.entities[5].open_toast_variants[0].open_toast") is not None
          and live_text("wandering_inn_game/data/maps/inn/inn.json",
                        "$.entities[29].door_when.open_toast") is not None)
    check("resolve_path returns None for a path that does not exist",
          live_text("wandering_inn_game/data/maps/inn/inn.json",
                    "$.entities[9999].observe") is None)

    # ---- 11. PHASE 4 advisory metrics -------------------------------------
    # Everything here proves the COUNTERS COUNT and the report is reproducible.
    # None of it asserts a corpus number: a metric leg that says "the corpus
    # still has N of X" inverts the moment the pass succeeds, which is the H1
    # bug this file has now been bitten by four times. Synthetic probes and
    # structural properties only.

    # 11a. narrator vs spoken, on synthetic rows (one per renderer shape) --
    #      these cannot drift with the corpus -- plus the partition property on
    #      the real one.
    def prow(corpus, field, path, opt=False):
        return {"corpus": corpus, "field": field, "field_path": path,
                "is_player_option": opt}

    probes = [
        (prow("dialogue", "text", "$.nodes.hub.text"), ("spoken", "node-line")),
        (prow("dialogue", "text", "$.nodes.hub.options[0].text", True),
         ("spoken", "player-option")),
        (prow("dialogue", "text_bank", "$.text_banks.just_passing_through"),
         ("spoken", "bank-line")),
        (prow("dialogue", "toast", "$.nodes.hub.options[0].effects[0].toast", True),
         ("narrator", "effect-toast")),
        (prow("maps", "observe", "$.entities[0].observe"), ("narrator", "narration")),
        (prow("maps", "text", "$.entities[0].dialogue[0].text"),
         ("spoken", "ambient-speech")),
        (prow("maps", "friendly_line", "$.entities[0].friendly_line"),
         ("spoken", "npc-friendly-line")),
        (prow("maps", "copy", "$.entities[2].board_rumors[0].copy"),
         ("narrator", "diegetic-document")),
        (prow("maps", "text", "$.arrival_toasts[0].text"), ("narrator", "narration")),
        (prow("maps", "locked_toast", "$.entities[3].locked_toast"),
         ("narrator", "narration")),
    ]
    bad_v = [f"{p['field_path']} -> {voice_of(p)} want {w}"
             for p, w in probes if voice_of(p) != w]
    check(f"voice_of classifies all {len(probes)} renderer shapes", not bad_v,
          str(bad_v))
    check("every live string is narrator XOR spoken",
          {voice_of(r)[0] for r in rows} == {"narrator", "spoken"})
    spoken_maps = {r["id"] for r in m if voice_of(r)[0] == "spoken"}
    want_spoken = {r["id"] for r in m
                   if r["field"] == "friendly_line"
                   or (r["field"] == "text" and ".dialogue[" in r["field_path"])}
    check("spoken map strings == friendly_line + ambient dialogue[].text",
          spoken_maps == want_spoken,
          str(sorted(spoken_maps ^ want_spoken)[:3]))
    check("the only narrator dialogue strings are the option-effect toasts",
          {r["id"] for r in d if voice_of(r)[0] == "narrator"}
          == {r["id"] for r in d if r["field"] == "toast"})

    # 11b. the anon split partitions the seven-word union, on every string
    part = [r["id"] for r in rows if r["tells"]["anon_agent"]
            != r["tells"]["anon_motive"] + r["tells"]["anon_indef"]]
    check("anon 7-word count == 4-word motive + 3-word indefinite, every string",
          not part, str(part[:3]))
    check("anon_motive fires on 'Someone carved joy here'",
          tells("Someone carved joy here, and meant it to last.")["anon_motive"] == 1)
    ind = tells("Something moved. Nobody came. Anyone could see it.")
    check("anon_motive ignores the three present indefinites",
          ind["anon_motive"] == 0 and ind["anon_indef"] == 3,
          f"motive={ind['anon_motive']} indef={ind['anon_indef']}")

    # 11c. the widened which-from (the floodplains/garden lane's two-word gap)
    check("which_from counts a determiner+noun phrase (the reported gap)",
          tells("It goes still when you crouch, which from a razorbeak is an "
                "invitation.")["which_from"] == 1)
    check("which_from still counts the one-word case it always caught",
          tells("Pisces says nothing, which from him is applause.")["which_from"] == 1)
    long_np = "A silence which from the whole of the assembled court is applause."
    check("which_from stops at three words, so long NPs are not silently counted",
          tells(long_np)["which_from"] == 0)
    check("...and a long NP IS surfaced as a near-miss instead",
          bool(RE_WHICH_LONG_NP.search(long_np)))
    check("the alternate-copula variant is a near-miss, not a count",
          bool(RE_WHICH_ALT_VERB.search(
              "the cloth sitting there with nothing on it, which in this city "
              "means nobody slows down"))
          and tells("which in this city means nobody slows down")["which_from"] == 0)

    # 11d. the CAPS lettering proxy, incl. the new "in a ... hand" form
    check("CAPS lettering cue accepts the 'in a ... hand' form (§8 blind spot)",
          tells("Set down in a clerk's hand: PASSES ARE PROPERTY OF THE CITY."
                )["caps_lettering_ctx"])
    check("chalked / stamped / stencilled were already covered",
          all(lettering_cue(t) for t in
              ("Beside it, chalked: HELD.",
               "A stamped plate: PERMIT.",
               "A stencilled plate: PERMIT AND STAMP REQUIRED.")))
    bare = tells("It is not a statue. STATUES do not turn.")
    check("CAPS with no lettering context stays BARE",
          bool(bare["caps"]) and not bare["caps_lettering_ctx"],
          f"caps={bare['caps']} cue={bare['caps_cue']!r}")

    # 11e. ending shapes: the fixtures, and taxonomy closure over the corpus
    shp = [("Leave it that way.", "instruction"),
           ("Down you go.", "instruction"),
           ("The bones rise and fall into step behind you.", "motion"),
           ("Browsing, or selling?", "unresolved"),
           ("The dark swallows the light three steps down—", "interruption"),
           ("It has not looked directly at you once.", "absence"),
           ("The clerk's window is open.", "fact")]
    bad_s = [f"{t!r} -> {ending_shape(t)} want {w}"
             for t, w in shp if ending_shape(t) != w]
    check(f"ending_shape assigns all {len(shp)} documented fixtures", not bad_s,
          str(bad_s))
    check("every live string scores inside the six-shape taxonomy",
          {ending_shape(r["text"]) for r in rows} <= set(ENDING_SHAPES))
    print("  note documented §9 divergence: 'Nobody came back to make the "
          f"ninety-third.' -> {ending_shape('Nobody came back to make the ninety-third.')}"
          " (the bible's table calls it fact; see the report's §8 header)")

    # 11f. the report generates deterministically and writes both artifacts
    d1, d2 = report_data(DOCS), report_data(DOCS)
    check("report data is byte-deterministic across two builds",
          json.dumps(d1, sort_keys=True) == json.dumps(d2, sort_keys=True))
    md1 = render_report(d1)
    check("report markdown is byte-deterministic", md1 == render_report(d2))
    with tempfile.TemporaryDirectory() as td:
        rc = cmd_report(td, DOCS)
        pmd, pjs = Path(td) / "phase4-report.md", Path(td) / "phase4-report.json"
        check("report writes both artifacts and exits 0",
              rc == 0 and pmd.exists() and pjs.exists())
        check("the written report equals the rendered one, byte for byte",
              rtext(pmd) == md1
              and json.dumps(rjson(pjs), sort_keys=True)
              == json.dumps(json.loads(json.dumps(d1)), sort_keys=True))

    # 11g. honest denominators: every bucket splits exactly three ways
    mismatch = []
    for reg, cell in sorted(d1["by_region"].items()):
        for v in ("narrator", "spoken"):
            tot = cell[v]["all"]["strings"]
            parts = sum(cell[v][s]["strings"] for s in STATUSES)
            if tot != parts:
                mismatch.append(f"{reg}/{v}: {tot} != {parts}")
        if cell["all"]["strings"] != cell["narrator"]["all"]["strings"] \
                + cell["spoken"]["all"]["strings"]:
            mismatch.append(f"{reg}: voices do not sum to all")
    check("every reported bucket == touchable + protected + holdout, and "
          "narrator + spoken == all", not mismatch, str(mismatch[:3]))
    check("the report's pin counts come from the frozen artifacts",
          d1["_pins"]["protected_keeps"] == len(rjson(DOCS / "protected-keeps.json")["keeps"])
          and d1["_pins"]["holdout"] == len(rjson(DOCS / "holdout.json")["ids"]))

    # 11h. landmark grants + the §5 reserve arithmetic
    check("landmark reserve: ceiling == spent + remaining",
          LANDMARK_CEILING_BEATS == LANDMARK_BEATS_SPENT + LANDMARK_RESERVE_LEFT,
          f"{LANDMARK_CEILING_BEATS} == {LANDMARK_BEATS_SPENT} + "
          f"{LANDMARK_RESERVE_LEFT}")
    check("landmark reserve is not overdrawn", LANDMARK_RESERVE_LEFT >= 0,
          f"{LANDMARK_RESERVE_LEFT} left")
    check("every landmark grant binds to a live inventory id",
          not [g for g in LANDMARK_GRANTS if g not in {r["id"] for r in rows}],
          str([g for g in LANDMARK_GRANTS if g not in {r["id"] for r in rows}]))
    check("no grant duplicates a heuristic landmark (a grant is an ALLOCATION)",
          not (set(LANDMARK_GRANTS) & (lm_ids | set(LANDMARK_DISPOSITIONS))))
    regf = DOCS / "landmark-registry.json"
    reg_committed = rjson(regf) if regf.exists() else {"strings": []}
    check("committed landmark-registry.json holds every ruled landmark + grant",
          sorted(s["id"] for s in reg_committed["strings"])
          == sorted(lm_ids | set(LANDMARK_GRANTS)),
          f"{len(reg_committed['strings'])} rows on disk")
    check("committed registry restates the reserve as spent/remaining",
          reg_committed.get("_reserve", {}).get("remaining_beats")
          == LANDMARK_RESERVE_LEFT
          and reg_committed.get("_reserve", {}).get("spent_beats")
          == LANDMARK_BEATS_SPENT)
    lm_drift = [s["id"] for s in reg_committed["strings"]
                if live_text(s["file"], s["field_path"]) != s["text"]]
    check("every registry row's recorded text IS the live text "
          "(a KEEP-AS-IS grant changes no bytes)", not lm_drift, str(lm_drift[:3]))

    print("self-test:", "PASS" if not fails else f"{len(fails)} FAILURES: {fails}")
    return 1 if fails else 0


