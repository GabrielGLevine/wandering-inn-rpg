def walk_dialogue_effect_prose(obj, path="$", under_effects=False):
    """Yield (json_path, value) for option-effect toasts. Nothing else in an
    `effects` block is prose; every other value there is an id or a flag."""
    if isinstance(obj, dict):
        for k, v in obj.items():
            if k.startswith("_"):
                continue
            p = f"{path}.{k}"
            if under_effects and k in DLG_EFFECT_PROSE_KEYS and isinstance(v, str):
                yield p, v
            elif not isinstance(v, str):
                yield from walk_dialogue_effect_prose(
                    v, p, under_effects or k == DLG_EFFECT_CONTAINER)
    elif isinstance(obj, list):
        for i, v in enumerate(obj):
            if not isinstance(v, str):
                yield from walk_dialogue_effect_prose(v, f"{path}[{i}]", under_effects)


def walk_dialogue_prose(data):
    """Yield (json_path, value, field) for every player-facing dialogue string.
    field is one of: text | text_bank | toast."""
    for p, t in GATE.walk_texts(data):
        yield p, t, ("text_bank" if RE_BANK_PATH.search(p) else "text")
    for p, t in walk_dialogue_effect_prose(data):
        yield p, t, "toast"


