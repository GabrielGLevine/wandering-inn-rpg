DEMOTION_TRIGGERS = (("closer_score", 2), ("neg_correction", 2), ("anon_agent", 2))


def demotion_triggers(t):
    return [k for k, thr in DEMOTION_TRIGGERS if t.get(k, 0) >= thr]


def is_demotion_candidate(register, t):
    return register in ("functional", "scenic") and bool(demotion_triggers(t))


def classified_records(rows, keeps, hold_set, named_work, overrides):
    """The map-prose classification records `all` writes per region -- factored
    out so `landmarks` and `report` build the SAME records instead of a second,
    drifting copy. `keeps`/`hold_set` are id containers; for the on-demand
    subcommands they are the COMMITTED artifacts (protected-keeps.json /
    holdout.json), which is what verify-untouched enforces."""
    out = []
    for r in rows:
        if r["corpus"] != "maps":
            continue
        reg, tag = classify_row(r, overrides)
        t = r["tells"]
        untouchable = r["id"] in keeps or r["id"] in hold_set
        trig = demotion_triggers(t)
        demote = is_demotion_candidate(reg, t) and not untouchable
        out.append({
            "id": r["id"], "region": r["region"], "file": r["file"],
            "field_path": r["field_path"], "field": r["field"],
            "register": reg, "tag": tag,
            "entity_id": (r["entity"] or {}).get("entity_id"),
            "display_name": (r["entity"] or {}).get("display_name"),
            "word_count": r["word_count"],
            "closer_score": t["closer_score"],
            "anon_agent": t["anon_agent"],
            "neg_correction": t["neg_correction"],
            "demotion_candidate": demote,
            "demotion_triggers": trig if demote else [],
            "issue_named_work": named_work.get(r["id"]),
            "holdout": r["id"] in hold_set,
            "protected": r["id"] in keeps,
            "text": r["text"],
        })
    return out


# ---- blind sets --------------------------------------------------------------
def blind_pool(rows, corpus):
    return [r for r in rows
            if r["corpus"] == corpus and r["word_count"] >= BLIND_MIN_WORDS]


def make_blind(rows, corpus):
    pool = blind_pool(rows, corpus)
    rng = random.Random(SEED)
    picked = rng.sample(sorted(pool, key=lambda r: r["id"]),
                        min(BLIND_SAMPLE_N, len(pool)))
    rng.shuffle(picked)
    return picked


BLIND_HEADER = """# BLIND REVIEW VIEW -- {corpus}
# GH#397. {n} strings, shuffled with random.Random({seed}). python {py}.
# Metadata deliberately stripped: no filenames, no speakers, no schema keys,
# no region. Row numbers are the ONLY handle; {key} maps them back.
# Read each row cold. Score per review-rubric.md. Do not seek context.
# ---------------------------------------------------------------------------

"""


def render_blind(picked, corpus, seed, key_file):
    body = BLIND_HEADER.format(corpus=corpus, n=len(picked), seed=seed, py=PY,
                               key=key_file)
    for i, r in enumerate(picked, 1):
        # single-line normalization keeps the review view uniform; the
        # inventory holds the byte-exact original.
        body += f"{i:3}. {' '.join(r['text'].split())}\n\n"
    return body


def write_blind(picked, corpus, outdir):
    wtext(Path(outdir) / f"sample-{corpus}-blind.txt",
          render_blind(picked, corpus, SEED, "sample-key.json"))
    return {str(i): r["id"] for i, r in enumerate(picked, 1)}


