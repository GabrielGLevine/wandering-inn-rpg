HEATMAP_WARNING = """> ## ⚠ THE RANKING DOES NOT GRANT PERMISSION TO EDIT
>
> **Holdout ids and protected keeps are UNTOUCHABLE by Phase 3, regardless of
> where their graph ranks here.** A graph at the top of this table may be
> mostly holdout; a graph with one flagged node may carry the corpus's most
> important protected keep. The `keeps` and `holdout` columns below are the
> counts per graph and the exact ids are listed in §*Untouchable ids per
> graph*. Before and after any Phase 3 edit, run:
>
> ```
> python3 qa/scripts/extract_prose.py verify-untouched --dir docs/prose-naturalization
> ```
>
> It exits 1 with a diff list if any holdout or protected-keep string has
> moved a byte. That is the mechanical guard; this table is only a reading
> order.
"""


def _ref(row_id, text, blind_ids):
    """Blind-set hygiene (fix M10): a string that appears in a blind sample is
    referenced by id + first six words, never quoted in full. The blind read
    is the acceptance instrument and this doc must not contaminate it."""
    if row_id in blind_ids:
        words = " ".join(text.split()).split()
        return f"`{row_id}` — \"{' '.join(words[:6])}…\" *(blind row; text withheld)*"
    return f"`{row_id}`\n  > {' '.join(text.split())}"


def cmd_heatmap(rows, out, keeps=None, hold_set=None, blind_ids=None):
    """Per-dialogue-file closer density + shared-geometry indicators, ranked,
    so Phase 3 picks its top-N graphs by evidence instead of by vibe."""
    keeps = keeps if keeps is not None else {}
    hold_set = hold_set if hold_set is not None else set()
    blind_ids = blind_ids if blind_ids is not None else set()
    SHAPES = ("neg_correction", "which_from", "the_way_x", "noun_repeat_wit")
    per = collections.defaultdict(lambda: {
        "nodes": 0, "opts": 0, "flagged": 0, "opt_flagged": 0, "words": 0,
        "shapes": collections.Counter(), "opt_shapes": collections.Counter(),
        "speakers": set(), "worst": [], "keeps": [], "holdout": []})
    for r in rows:
        if r["corpus"] != "dialogue":
            continue
        g = per[r["graph"]]
        t = r["tells"]
        g["words"] += r["word_count"]
        g["speakers"].add(r["speaker"])
        if r["id"] in keeps:
            g["keeps"].append(r["id"])
        if r["id"] in hold_set:
            g["holdout"].append(r["id"])
        # ONE POPULATION FOR THE RANKING (fix M5). Density, shape hits and the
        # shared-geometry term are all computed over NARRATOR/NPC nodes only.
        # Player options are a different authorial surface (they are the
        # player's voice, not the narrator's) and mixing them into the
        # numerator while excluding them from the denominator was the defect.
        # They get their own reported columns and no vote in the score.
        if r["is_player_option"]:
            g["opts"] += 1
            if t["closer_score"] >= 2:
                g["opt_flagged"] += 1
            for s in SHAPES:
                g["opt_shapes"][s] += t[s]
        else:
            g["nodes"] += 1
            for s in SHAPES:
                g["shapes"][s] += t[s]
            if t["closer_score"] >= 2:
                g["flagged"] += 1
                g["worst"].append((t["closer_score"], r["field_path"], r["text"], r["id"]))
    # shared geometry: how many OTHER graphs use each shape this graph uses
    shape_graphs = {s: {g for g, v in per.items() if v["shapes"][s]} for s in SHAPES}
    # Volume-shrunk density. A 1-node graph with 1 flagged node has raw
    # density 100% and is not a graph worth a pass; SHRINK pulls small-n rows
    # toward 0 (Laplace-style, denominator + SHRINK_K) so the ranking surfaces
    # graphs with enough evidence to judge. Raw density stays in the table.
    SHRINK_K = 6
    ranked = []
    for g, v in per.items():
        dens = v["flagged"] / v["nodes"] if v["nodes"] else 0.0
        adj = v["flagged"] / (v["nodes"] + SHRINK_K)
        # COUNT-SCALED shared geometry (fix M6). The old term was a flat +4-ish
        # bonus for merely USING a common shape once, which made "has one
        # negation" worth as much as "has five". Now each instance is weighted
        # by how many OTHER graphs share that shape, so the distributional
        # complaint the issue actually makes is what the number measures.
        shared = sum(v["shapes"][s] * (len(shape_graphs[s]) - 1) for s in SHAPES)
        ranked.append({
            "graph": g, "nodes": v["nodes"], "opts": v["opts"], "words": v["words"],
            "flagged": v["flagged"], "opt_flagged": v["opt_flagged"],
            "density": dens, "adj_density": adj,
            "shapes": dict(v["shapes"]), "opt_shapes": dict(v["opt_shapes"]),
            "shared_geometry": shared,
            "keeps": sorted(v["keeps"]), "holdout": sorted(v["holdout"]),
            "speakers": sorted(x for x in v["speakers"] if x),
            "score": round(adj * 100 + shared * 0.5, 2),
            "worst": sorted(v["worst"], reverse=True)[:2],
        })
    ranked.sort(key=lambda x: (-x["score"], x["graph"]))
    L = []
    L.append("# Dialogue graph heatmap — GH#397 Phase 3 targeting\n")
    L.append(gen_note("heatmap") + "\n")
    L.append(HEATMAP_WARNING)
    L.append("Acceptance criterion 4: residual dialogue work is targeted by "
             "graph-level evidence, not a mandatory second rewrite of every "
             "file. This is that evidence.\n")
    L.append("**How to read it.** `density` = share of narrator/NPC `text` "
             "strings whose final sentence trips the button smoke score "
             "(>=2 of 5; see review-rubric.md §4). One population runs the "
             "ranking: narrator/NPC nodes. Player options are the player's "
             "voice, not the narrator's, so their flagged count and shape hits "
             "are reported in their own columns and do not enter the score. "
             "`shared geom` = every instance of a rhetorical shape this graph "
             "uses, weighted by how many OTHER graphs use the same shape — the "
             "issue's complaint is distributional, so a shape is damning in "
             "proportion to both its frequency here and its commonness "
             "elsewhere. `score` = adj_density*100 + shared_geom*0.5. "
             "**These are smoke detectors. A high row is a graph worth "
             "READING, never a graph proven bad**; a low row is not a "
             "clearance.\n")
    L.append(f"Corpus: {len(per)} graphs, "
             f"{sum(v['nodes'] for v in per.values())} narrator/NPC strings, "
             f"{sum(v['opts'] for v in per.values())} player options. "
             f"Untouchable in dialogue: {sum(len(x['keeps']) for x in ranked)} "
             f"protected keeps, {sum(len(x['holdout']) for x in ranked)} "
             "holdout strings.\n")
    L.append("`density` is raw; `adj` is the volume-shrunk density the ranking "
             f"actually uses (flagged / (nodes + {SHRINK_K})), so a 1-node graph "
             "cannot top the list on a single hit.\n")
    L.append("| # | graph | nodes | flagged | density | adj | opts | opt flagged "
             "| shared geom | shape hits | keeps | holdout | score |")
    L.append("|--:|---|--:|--:|--:|--:|--:|--:|--:|---|--:|--:|--:|")
    for i, x in enumerate(ranked, 1):
        sh = ", ".join(f"{k.replace('_', ' ')} {v}"
                       for k, v in sorted(x["shapes"].items()) if v) or "—"
        mark = " ⛔" if x["graph"].startswith("riverfarm") else ""
        L.append(f"| {i} | `{x['graph']}`{mark} | {x['nodes']} | {x['flagged']} | "
                 f"{x['density']:.0%} | {x['adj_density']:.0%} | {x['opts']} | "
                 f"{x['opt_flagged']} | {x['shared_geometry']} | {sh} | "
                 f"{len(x['keeps'])} | {len(x['holdout'])} | {x['score']:.1f} |")
    L.append("\n⛔ = `riverfarm_*`: **excluded from the Phase 3 shortlist by "
             "controller ruling** — riverfarm is out of scope for this pass. "
             "The rows stay in the table because dropping them from the "
             "measurement would corrupt the shared-geometry denominators every "
             "other graph is scored against; they are simply not work.\n")

    short = [x for x in ranked if not x["graph"].startswith("riverfarm")][:10]
    L.append("## Top 10 by score — the Phase 3 shortlist\n")
    L.append("riverfarm_* graphs are skipped here per the ruling above.\n")
    for i, x in enumerate(short, 1):
        L.append(f"### {i}. `{x['graph']}` — density {x['density']:.0%} "
                 f"({x['flagged']}/{x['nodes']}), shared geom "
                 f"{x['shared_geometry']}, score {x['score']:.1f}")
        L.append(f"Speakers: {', '.join(x['speakers']) or 'narrator'}. "
                 f"{x['words']} words. **Untouchable here: "
                 f"{len(x['keeps'])} keeps, {len(x['holdout'])} holdout.**\n")
        for sc, fp, t, rid in x["worst"]:
            L.append(f"- smoke {sc}/5 · " + _ref(rid, t, blind_ids))
        L.append("")

    L.append("## Untouchable ids per graph\n")
    L.append("`K` = protected keep (never rewritten, even where it trips a "
             "rule — the keep outranks the rule). `H` = holdout (Phase 5 reads "
             "it untouched; editing it destroys the exit comparison). Absence "
             "from this list is not permission to rewrite: the default action "
             "on a string nobody flagged is to leave it alone.\n")
    any_un = False
    for x in ranked:
        if not (x["keeps"] or x["holdout"]):
            continue
        any_un = True
        L.append(f"- **`{x['graph']}`** — {len(x['keeps'])}K / "
                 f"{len(x['holdout'])}H")
        for i in x["keeps"]:
            L.append(f"  - K `{i}`")
        for i in x["holdout"]:
            L.append(f"  - H `{i}`")
    if not any_un:
        L.append("_(none — which would itself be a bug.)_")
    L.append("")
    wtext(out, "\n".join(L) + "\n")
    return ranked


# ---- verify-untouched (fix C1's mechanical guard) ----------------------------
def cmd_verify_untouched(docdir):
    """Recompute the live text at every holdout id and every protected-keep id
    and diff it against the committed baseline inventory. This is the tripwire
    Phase 2, Phase 3 and issue close all run. Exit 1 on any drift."""
    docdir = Path(docdir)
    base = {r["id"]: r for r in load_inventory(docdir / "inventory.jsonl")}
    hold = rjson(docdir / "holdout.json")["ids"]
    keeps = rjson(docdir / "protected-keeps.json")["keeps"]
    targets = ([(i, "holdout") for i in hold]
               + [(i, "protected-keep") for i in sorted(keeps)])
    bad = []
    for rid, kind in targets:
        row = base.get(rid)
        if row is None:
            bad.append((kind, rid, "NOT IN BASELINE INVENTORY", ""))
            continue
        cur = live_text(row["file"], row["field_path"])
        if cur is None:
            bad.append((kind, rid, "FIELD PATH NO LONGER RESOLVES", row["text"]))
        elif cur != row["text"]:
            bad.append((kind, rid, cur, row["text"]))
    print(f"verify-untouched: {len(hold)} holdout + {len(keeps)} protected "
          f"= {len(targets)} untouchable strings checked "
          f"(baseline {docdir/'inventory.jsonl'})")
    if not bad:
        print("  ok   every untouchable string is byte-identical to baseline")
        return 0
    print(f"  FAIL {len(bad)} untouchable strings have drifted:")
    for kind, rid, cur, was in bad:
        print(f"\n  [{kind}] {rid}")
        print(f"    baseline: {' '.join(was.split())[:160]}")
        print(f"    current : {' '.join(str(cur).split())[:160]}")
    return 1


# ---- classification self-probe (fix I4) --------------------------------------
def cmd_classify_probe(seed, n):
    """Stratified read-out of the register heuristic, for hand-judging. Prints
    n/4 rows per register with a fixed, documented seed so the probe can be
    re-run and audited. Reports nothing about correctness -- a human reads the
    rows and records the disagreement count."""
    rows = build_inventory()
    ov = load_overrides()
    per = collections.defaultdict(list)
    for r in rows:
        if r["corpus"] != "maps":
            continue
        reg, tag = classify_row(r, ov)
        per[reg].append((r, tag))
    rng = random.Random(seed)
    k = max(1, n // len(per))
    print(f"# classification self-probe — seed {seed}, python {PY}, "
          f"{k} rows × {len(per)} registers")
    for reg in sorted(per):
        pool = sorted(per[reg], key=lambda x: x[0]["id"])
        pick = rng.sample(pool, min(k, len(pool)))
        for r, tag in pick:
            print(f"\n[{reg} / {tag}] {r['id']}")
            print(f"  field={r['field']} kind={(r['entity'] or {}).get('entity_kind')} "
                  f"banks={(r['entity'] or {}).get('banks')}")
            print(f"  > {' '.join(r['text'].split())}")
    return 0


