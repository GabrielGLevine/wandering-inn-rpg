def cmd_classify_probe(seed, n):
    """Stratified read-out of the register heuristic, for hand-judging. Prints
    n/4 rows per register with a fixed, documented seed so the probe can be
    re-run and audited. Reports nothing about correctness -- a human reads the
    rows and records the disagreement count."""
    rows = build_inventory()
    ov = load_overrides()
    per = collections.defaultdict(list)
    for r in rows:
        if r["corpus"] != "maps":
            continue
        reg, tag = classify_row(r, ov)
        per[reg].append((r, tag))
    rng = random.Random(seed)
    k = max(1, n // len(per))
    print(f"# classification self-probe — seed {seed}, python {PY}, "
          f"{k} rows × {len(per)} registers")
    for reg in sorted(per):
        pool = sorted(per[reg], key=lambda x: x[0]["id"])
        pick = rng.sample(pool, min(k, len(pool)))
        for r, tag in pick:
            print(f"\n[{reg} / {tag}] {r['id']}")
            print(f"  field={r['field']} kind={(r['entity'] or {}).get('entity_kind')} "
                  f"banks={(r['entity'] or {}).get('banks')}")
            print(f"  > {' '.join(r['text'].split())}")
    return 0


