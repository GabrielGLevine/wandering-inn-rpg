    """Independent path-based census of dialogue string keys. Mirror of the
    maps census (fix I1): a dialogue field the walker does not know about must
    surface as a REPORT, not as silently missing prose.

    -> (included Counter, excluded Counter, unknown Counter, {file: set(paths)})
    """
    inc, exc, unknown = collections.Counter(), collections.Counter(), collections.Counter()
    paths = {}

    def walk(o, keys, path, out):
        if isinstance(o, dict):
            for k, v in o.items():
                walk(v, keys + (k,), f"{path}.{k}", out)
        elif isinstance(o, list):
            for i, v in enumerate(o):
                walk(v, keys, f"{path}[{i}]", out)
        elif isinstance(o, str) and keys:
            k = keys[-1]
            if any(x.startswith("_") for x in keys):
                exc["_author-private"] += 1
            elif len(keys) >= 2 and keys[-2] in DLG_BANK_CONTAINERS:
                inc["text_bank"] += 1
                out.add(path)
            elif k in DLG_PROSE_KEYS:
                if o.startswith("@"):
                    exc["text (@ref = structure)"] += 1
                else:
                    inc["text"] += 1
                    out.add(path)
            elif k in DLG_EFFECT_PROSE_KEYS and DLG_EFFECT_CONTAINER in keys:
                inc["effects[].toast"] += 1
                out.add(path)
            elif k in DLG_KNOWN_NON_PROSE:
                exc[k] += 1
            else:
                unknown[k] += 1

    for f in sorted(GATE.DIALOGUE.glob("*.json")):
        out = set()
        walk(rjson(f), (), "$", out)
        paths[f.name] = out
    return inc, exc, unknown, paths


