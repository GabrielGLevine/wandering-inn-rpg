def build_keeps(rows, outdir=None):
    """Merge the issue's five with the lane-added list, and pin every entry to
    {file, field_path, exact_text} from the live inventory."""
    keeps, unresolved = resolve_issue_keeps(rows)
    by_id = {r["id"]: r for r in rows}
    for k, v in load_extra_keeps(outdir).items():
        if k in keeps:
            # The issue's own entry stays authoritative; the lane's note is
            # ADDED, not dropped. A collision is a signal, not a conflict: the
            # lane independently reached a line the issue already protects.
            keeps[k]["also"] = v
        else:
            keeps[k] = dict(v)
        r = by_id.get(k)
        if r:
            keeps[k]["file"] = r["file"]
            keeps[k]["field_path"] = r["field_path"]
            keeps[k]["exact_text"] = r["text"]
        else:
            unresolved.append(f"lane keep does not bind to an inventory id: {k}")
    return keeps, unresolved


