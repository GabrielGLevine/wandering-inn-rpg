# ---- io: one encoding, everywhere -------------------------------------------
def rtext(p):
    return Path(p).read_text(encoding="utf-8")


def wtext(p, s):
    p = Path(p)
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(s, encoding="utf-8")


def rjson(p):
    return json.loads(rtext(p))


def wjson(p, obj):
    wtext(p, json.dumps(obj, indent=1, sort_keys=True, ensure_ascii=False) + "\n")


