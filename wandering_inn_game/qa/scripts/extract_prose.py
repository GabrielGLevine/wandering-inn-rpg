# ---- holdout ----------------------------------------------------------------
def holdout_pool(rows, reserved_ids, blind_ids):
    """Eligibility is the SAME as the blind sets': >=6 words (fix I6). Phase 5
    reads the revised blind sample against the untouched holdout, and that
    comparison is only sound if the two views are drawn from one population --
    a holdout half-full of "Nothing there." is a different instrument.

    `reserved_ids` = protected keeps + issue-named work: every string that
    already has a disposition. Everything else is fair game."""
    return sorted(r["id"] for r in rows
                  if r["word_count"] >= BLIND_MIN_WORDS
                  and r["id"] not in reserved_ids and r["id"] not in blind_ids)


def make_holdout(rows, reserved_ids, blind_ids):
    pool = holdout_pool(rows, reserved_ids, blind_ids)
    rng = random.Random(SEED + 1)
    # 10% OF THE WHOLE INVENTORY, drawn from the eligible pool -- so the
    # holdout is a true tenth of the corpus, not a tenth of what's left over.
    n = min(round(len(rows) * HOLDOUT_FRACTION), len(pool))
    return sorted(rng.sample(pool, n))


