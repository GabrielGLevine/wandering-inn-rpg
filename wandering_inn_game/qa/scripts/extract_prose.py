# ---- field-path resolution ---------------------------------------------------
# The ONLY binding mechanism for protected keeps, holdout verification and the
# self-test's text-match leg. A field path survives reformatting; a line number
# does not, and a line number that silently re-points to a DIFFERENT string is
# the exact failure mode protected keeps exist to prevent (GH#397 fix I7).
RE_PATH_TOK = re.compile(r"\.([^.\[\]]+)|\[(\d+)\]")


def resolve_path(data, path):
    """Value at a walker-emitted json path, or None if any step is missing."""
    if not isinstance(path, str) or not path.startswith("$"):
        return None
    cur = data
    for m in RE_PATH_TOK.finditer(path):
        key, idx = m.group(1), m.group(2)
        if key is not None:
            if not isinstance(cur, dict) or key not in cur:
                return None
            cur = cur[key]
        else:
            i = int(idx)
            if not isinstance(cur, list) or i >= len(cur):
                return None
            cur = cur[i]
    return cur


_FILE_CACHE = {}


def live_text(repo_rel, field_path):
    """Current text at a repo-relative file + field path. Cached per process."""
    if repo_rel not in _FILE_CACHE:
        _FILE_CACHE[repo_rel] = rjson(REPO / repo_rel)
    v = resolve_path(_FILE_CACHE[repo_rel], field_path)
    return v if isinstance(v, str) else None


